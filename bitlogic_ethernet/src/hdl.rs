//! Verilog generation.
//!
//! bitlogic emits each step function as a purely combinational module with one
//! port per state leaf. For integration, [`unit_verilog`] wraps it in a
//! "unit": one packed state register with synchronous reset to zero, the
//! combinational step, and `s_<field>` outputs exposing the *current* registered
//! state leaves. Cross-unit signals use those registered outputs, so no
//! combinational path crosses between units.
use crate::{proto, rom, rx, status, tx};
use bitlogic::{Error, Logic, Port};
use std::fmt::Write;

const STATE: &str = "state_";

fn split(ports: &[Port]) -> (Vec<&Port>, Vec<&Port>) {
    ports.iter().partition(|p| p.name.starts_with(STATE))
}

/// Wrap `logic` (emitted as `<unit>_logic`) in a registered unit module `<unit>`.
pub fn unit_verilog(logic: &Logic, unit: &str) -> Result<String, Error> {
    let inner = format!("{unit}_logic");
    let mut text =
        String::from("// Generated by bitlogic_ethernet; do not edit.\n`timescale 1ns / 1ps\n");
    text.push_str(&logic.to_verilog(&inner)?);

    let (state_in, other_in) = split(logic.inputs());
    let (state_out, other_out) = split(logic.outputs());
    let shape = |ports: &[&Port]| -> Vec<(String, u8)> {
        ports.iter().map(|p| (p.name.clone(), p.width)).collect()
    };
    if state_in.is_empty() || shape(&state_in) != shape(&state_out) {
        return Err(Error(format!("{unit}: state input/output leaves differ")));
    }
    let width: usize = state_in.iter().map(|p| usize::from(p.width)).sum();

    let mut ports = vec!["input wire clk".to_string(), "input wire rst".to_string()];
    for p in &other_in {
        ports.push(format!("input wire [{}:0] i_{}", p.width - 1, p.name));
    }
    for p in &other_out {
        ports.push(format!("output wire [{}:0] o_{}", p.width - 1, p.name));
    }
    for p in &state_in {
        let field = &p.name[STATE.len()..];
        ports.push(format!("output wire [{}:0] s_{field}", p.width - 1));
    }
    writeln!(text, "\nmodule {unit}(\n    {}\n);", ports.join(",\n    ")).unwrap();
    writeln!(text, "    reg [{}:0] state = {width}'d0;", width - 1).unwrap();
    writeln!(text, "    wire [{}:0] next_state;", width - 1).unwrap();

    let mut connections = Vec::new();
    let mut offset = 0;
    for p in &state_in {
        let field = &p.name[STATE.len()..];
        let (lo, hi) = (offset, offset + usize::from(p.width) - 1);
        writeln!(text, "    assign s_{field} = state[{hi}:{lo}];").unwrap();
        connections.push(format!(".i_{}(state[{hi}:{lo}])", p.name));
        connections.push(format!(".o_{}(next_state[{hi}:{lo}])", p.name));
        offset += usize::from(p.width);
    }
    for p in other_in {
        connections.push(format!(".i_{0}(i_{0})", p.name));
    }
    for p in other_out {
        connections.push(format!(".o_{0}(o_{0})", p.name));
    }
    writeln!(
        text,
        "    {inner} step(\n        {}\n    );",
        connections.join(",\n        ")
    )
    .unwrap();
    writeln!(
        text,
        "    always @(posedge clk) begin\n        if (rst) state <= {width}'d0;\n        \
         else state <= next_state;\n    end\nendmodule"
    )
    .unwrap();
    Ok(text)
}

/// Every generated file as `(file name, contents)`.
pub fn generated_files() -> Result<Vec<(String, String)>, Error> {
    Ok(vec![
        (
            "rx_unit.v".into(),
            unit_verilog(&rx::rx_step::ir()?, "rx_unit")?,
        ),
        (
            "proto_unit.v".into(),
            unit_verilog(&proto::proto_step::ir()?, "proto_unit")?,
        ),
        (
            "tx_unit.v".into(),
            unit_verilog(&tx::tx_step::ir()?, "tx_unit")?,
        ),
        (
            "status_unit.v".into(),
            unit_verilog(&status::status_step::ir()?, "status_unit")?,
        ),
        ("template_rom.v".into(), rom::rom_verilog()),
    ])
}
