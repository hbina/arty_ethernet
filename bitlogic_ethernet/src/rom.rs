//! TX frame templates for the protocol unit, stored in a 512 x 9-bit ROM.
//!
//! Address `{arp, index[7:0]}`: the beacon template starts at 0 and the ARP
//! template at 256. Each entry is either a literal byte (bit 8 clear) or a
//! dynamic byte `0x100 | source << 4 | position` resolved by `proto_step`:
//!
//! | source | value | position |
//! |---|---|---|
//! | 0 | `request.dst_mac` | byte 0..=5, most significant first |
//! | 1 | `request.peer_mac` | byte 0..=5 |
//! | 2 | `request.peer_ip` | byte 0..=3 |
//! | 3..=11 | beacon counters (see [`COUNTER_SOURCES`]) | hex digit 0..=7 |
//!
//! The beacon text matches `beacon_payload_literal_byte` in the HLS design up
//! to `UP=`; this design appends ` FCS=`, ` ICMP=` and ` PEERS=` counters.
use crate::consts::*;
use std::fmt::Write;

pub const ROM_DEPTH: usize = 512;
pub const ARP_BASE: usize = 256;

/// Beacon fields in source order 3..=11, with their text labels.
pub const COUNTER_SOURCES: [(&str, u16); 9] = [
    ("RX", 3),
    ("RXQ", 4),
    ("RXP", 5),
    ("TXD", 6),
    ("ARP", 7),
    ("UP", 8),
    ("FCS", 9),
    ("ICMP", 10),
    ("PEERS", 11),
];

fn literal(bytes: &[u8]) -> impl Iterator<Item = u16> + '_ {
    bytes.iter().map(|&b| u16::from(b))
}

fn dynamic(source: u16, count: u16) -> impl Iterator<Item = u16> {
    (0..count).map(move |position| 0x100 | source << 4 | position)
}

fn mac_bytes(mac: u64) -> [u8; 6] {
    let b = mac.to_be_bytes();
    [b[2], b[3], b[4], b[5], b[6], b[7]]
}

/// Beacon frame body: broadcast header, EtherType 0x88B5, 171 text bytes.
pub fn beacon_template() -> Vec<u16> {
    let ip = FPGA_IP.to_be_bytes();
    let mut ip_text = String::new();
    for (k, octet) in ip.iter().enumerate() {
        write!(ip_text, "{}{octet:03}", if k == 0 { "" } else { "." }).unwrap();
    }
    let mut t: Vec<u16> = Vec::new();
    t.extend(literal(&mac_bytes(BROADCAST_MAC)));
    t.extend(literal(&mac_bytes(FPGA_MAC)));
    t.extend(literal(&DIAGNOSTIC_BEACON_ETHERTYPE.to_be_bytes()));
    t.extend(literal(
        format!("ARTY IP={ip_text} MAC={FPGA_MAC:012X}").as_bytes(),
    ));
    for (label, source) in COUNTER_SOURCES {
        // The HLS beacon reports UDP=00000000 between ARP and UP.
        if label == "UP" {
            t.extend(literal(b" UDP=00000000"));
        }
        t.extend(literal(format!(" {label}=").as_bytes()));
        t.extend(dynamic(source, 8));
    }
    assert_eq!(t.len() as u64, BEACON_FRAME_BODY_LEN);
    t
}

/// ARP frame body used for replies and gratuitous announcements.
pub fn arp_template() -> Vec<u16> {
    let mut t: Vec<u16> = Vec::new();
    t.extend(dynamic(0, 6));
    t.extend(literal(&mac_bytes(FPGA_MAC)));
    t.extend(literal(&ARP_ETHERTYPE.to_be_bytes()));
    // htype=1, ptype=0x0800, hlen=6, plen=4, oper=2 (reply)
    t.extend(literal(&[0x00, 0x01, 0x08, 0x00, 0x06, 0x04, 0x00, 0x02]));
    t.extend(literal(&mac_bytes(FPGA_MAC)));
    t.extend(literal(&FPGA_IP.to_be_bytes()));
    t.extend(dynamic(1, 6));
    t.extend(dynamic(2, 4));
    assert_eq!(t.len() as u64, ARP_FRAME_BODY_LEN);
    t
}

pub fn rom_contents() -> Vec<u16> {
    let mut rom = vec![0; ROM_DEPTH];
    for (k, v) in beacon_template().into_iter().enumerate() {
        rom[k] = v;
    }
    for (k, v) in arp_template().into_iter().enumerate() {
        rom[ARP_BASE + k] = v;
    }
    rom
}

/// Synchronous ROM with one cycle of read latency, like the RAMs.
pub fn rom_verilog() -> String {
    let mut text = String::from(
        "// Generated by bitlogic_ethernet; do not edit.\n`timescale 1ns / 1ps\n\
         module template_rom(\n    input wire clk,\n    input wire [8:0] addr,\n    \
         output reg [8:0] data\n);\n    initial data = 9'h000;\n    \
         always @(posedge clk) begin\n        case (addr)\n",
    );
    for (address, value) in rom_contents().into_iter().enumerate() {
        if value != 0 {
            writeln!(text, "            9'd{address}: data <= 9'h{value:03x};").unwrap();
        }
    }
    text.push_str("            default: data <= 9'h000;\n        endcase\n    end\nendmodule\n");
    text
}
